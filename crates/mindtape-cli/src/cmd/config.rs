//! `mt config` inspects the effective merged configuration.
//!
//! Read-only: never writes. `show` (the default action) prints the effective
//! config assembled from every layer (embedded floor, XDG global defaults,
//! ancestor `.mindtape/defaults.toml` files, the project's own
//! `.mindtape/config.toml`). `--origin` lists the contributing layers instead,
//! then the rules, keys and parameters that packs set. `--resolved` prints the
//! config `mt` uses, every default filled in. `--defaults` prints just
//! the embedded floor, independent of any project. `schema` prints the JSON
//! Schema for `.mindtape/config.toml`, generated by the same
//! [`mindtape::config_schema_json`] that `mt install` writes to disk.

use std::path::Path;

use crate::diag::Result;
use mindtape::{
    LayerSource, PackOrigin, ParamOrigin, RuleOrigin, config_schema_json, embedded_defaults,
    load_config_layered,
};
use serde::Serialize;

use crate::cmd::schema::CONFIG_SHOW;
use crate::render::envelope::Envelope;
use crate::util;

/// Arguments for `config`.
#[derive(Debug, clap::Args)]
pub struct ConfigArgs {
    #[command(subcommand)]
    action: Option<ConfigAction>,
}

/// `mt config` sub-actions.
#[derive(Debug, clap::Subcommand)]
enum ConfigAction {
    /// Print the config mt uses, with every layer merged.
    ///
    /// This is the default.
    Show(ShowArgs),
    /// Print the JSON Schema for `.mindtape/config.toml`.
    ///
    /// Works outside a project.
    Schema,
}

/// Arguments for `mt config show`.
// Four flags, three of them a view: clap spells each view as its own `--flag`,
// so the parser, not the type, is where they exclude each other. An enum would
// need a hand-written parse plus aliases to offer the same three switches.
#[allow(clippy::struct_excessive_bools)]
#[derive(Debug, Clone, Default, clap::Args)]
pub struct ShowArgs {
    /// List the layers the config comes from, instead of the config.
    ///
    /// The layers come lowest priority first. Each rule, each key a pack set
    /// and each pack parameter then reports the layer or pack it comes from.
    #[arg(long, alias = "sources", conflicts_with_all = ["defaults", "resolved"])]
    pub origin: bool,

    /// Print only the built-in defaults.
    ///
    /// Works outside a project.

    #[arg(long, conflicts_with_all = ["origin", "resolved"])]
    pub defaults: bool,

    /// Print the config mt uses, with every default filled in.
    ///
    /// The default view prints what the layers set, so it reads as a config
    /// file. This one also prints the value behind each key a layer left
    /// unset, and the result reads back as the same config.
    #[arg(long, conflicts_with_all = ["origin", "defaults"])]
    pub resolved: bool,

    /// Print JSON instead of TOML.
    #[arg(long, conflicts_with_all = ["origin", "defaults"])]
    pub json: bool,
}

/// Run the `config` command.
///
/// # Errors
/// Returns an error if the current directory is not inside a `Mindtape`
/// project (not required for `--defaults`, which is project-independent), or
/// the layered config fails to load.
pub fn run(args: &ConfigArgs) -> Result<()> {
    let show_args = match &args.action {
        None => ShowArgs::default(),
        Some(ConfigAction::Show(show_args)) => show_args.clone(),
        Some(ConfigAction::Schema) => {
            print!("{}", render_schema());
            return Ok(());
        }
    };
    if show_args.defaults {
        println!("{}", embedded_defaults().trim_end());
        return Ok(());
    }
    let root = util::resolve_root()?;
    let text = if show_args.origin {
        render_origin(&root)?
    } else {
        render_effective(&root, show_args.json, show_args.resolved)?
    };
    print!("{text}");
    Ok(())
}

/// The object `mt config show --json` prints: the merged config under
/// `config`.
#[derive(Debug, Serialize, schemars::JsonSchema)]
pub struct ConfigShowPayload {
    /// The merged table, shaped as `.mindtape/config.toml`. The schema
    /// describes it through [`mindtape::Config`], the type it deserializes to.
    #[schemars(with = "mindtape::Config")]
    pub config: toml::Table,
}

/// Render the effective config for `root` as TOML (or, with `json`, a
/// `$schema` envelope whose `config` holds pretty-printed JSON) text. Without
/// `resolved`, it emits the merged `toml::Table` directly, the same document
/// that feeds `Config`'s typed deserialization: the keys the layers set, and
/// nothing else. With `resolved`, it emits the loaded [`mindtape::Config`]
/// written back out, defaults included.
///
/// # Errors
/// Returns an error if any config layer fails to load or the document fails to
/// serialize.
pub(crate) fn render_effective(root: &Path, json: bool, resolved: bool) -> Result<String> {
    let table = if resolved {
        resolved_table(root)?
    } else {
        mindtape::merged_config_table(root)?
    };
    if json {
        let payload = ConfigShowPayload { config: table };
        return Ok(format!(
            "{}\n",
            serde_json::to_string_pretty(&Envelope::new(CONFIG_SHOW, payload))?
        ));
    }
    Ok(toml::to_string(&table)?)
}

/// The config `mt` uses for `root`, every default filled in, as a table shaped
/// as `.mindtape/config.toml`: the loaded [`mindtape::Config`] written back
/// out. Unlike the merged table, a rule with no `severity` carries the `warn`
/// it reports at. `extends`, `disable` and `pack-sources` are absent, because
/// they say how the layers combine rather than what the config does.
///
/// A path a pack declared prints as it resolves, relative to `root`. The
/// document then reads back as the same config. The declared text would
/// re-point at the project root, since a pack's paths resolve from the pack's
/// own directory.
///
/// # Errors
/// Returns an error if the config fails to load or to serialize. A [`Config`]
/// always serializes as a table.
///
/// [`Config`]: mindtape::Config
fn resolved_table(root: &Path) -> Result<toml::Table> {
    let mut config = mindtape::load_config(root)?;
    rewrite_pack_paths(&mut config, root);
    Ok(toml::Value::try_from(&config)?
        .as_table()
        .cloned()
        .unwrap_or_default())
}

/// Replace each path a pack declared with the form that reads at the project
/// root: the absolute path it resolves to, made relative to `root` when it
/// sits under it. A path outside the root stays absolute, which reads back
/// too. A path the project declared already reads at the root, so it stays as
/// it is.
fn rewrite_pack_paths(config: &mut mindtape::Config, root: &Path) {
    for rule in &mut config.tasks.rules {
        if let Some(check) = &mut rule.check
            && let Some(resolved) = check.resolved_typst().map(Path::to_path_buf)
        {
            check.typst = root_form(&resolved, root);
        }
    }
    for spec in &mut config.tasks.collectors {
        if let mindtape::CollectorQuery::Typst(query) = &mut spec.query
            && let Some(resolved) = query.resolved_typst().map(Path::to_path_buf)
        {
            query.typst = root_form(&resolved, root);
        }
    }
    for spec in config.dicts.values_mut() {
        if let Some(path) = &spec.path {
            spec.path = Some(root_form(Path::new(path), root));
        }
    }
}

/// `path` as the resolved view prints it: relative to the project root when it
/// sits under it, else absolute. Either form reads back from the root.
fn root_form(path: &Path, root: &Path) -> String {
    mindtape::display_path(mindtape::relative_to(path, root))
}

/// Render the contributing layers for `root`, one per line, in the same
/// precedence order [`load_config_layered`] returns them. A blank line then
/// leads, as far as any exist, one `rule <label>: <origin>` line per rule,
/// one `key <path>: <origin>` line per key a pack set, and one `param <name> =
/// <value>: <set by>, for pack <pack>` line per pack parameter. An origin
/// references the pack (`pack mindtape:tasks`, `pack acme:commits` or
/// `pack <path>`) or the layer.
///
/// # Errors
/// Returns an error if the layered config fails to load.
pub(crate) fn render_origin(root: &Path) -> Result<String> {
    let (config, sources, rule_origins) = load_config_layered(root)?;
    let mut out = String::new();
    for source in &sources {
        out.push_str(&describe_source(source));
        out.push('\n');
    }
    let mut lines: Vec<String> = rule_origins
        .iter()
        .map(|entry| {
            format!(
                "rule {}: {}",
                entry.label,
                describe_rule_origin(&entry.origin)
            )
        })
        .collect();
    lines.extend(
        config
            .key_origins()
            .map(|entry| format!("key {}: {}", entry.key, describe_rule_origin(&entry.origin))),
    );
    lines.extend(config.param_origins().map(describe_param));
    if !lines.is_empty() {
        out.push('\n');
        for line in lines {
            out.push_str(&line);
            out.push('\n');
        }
    }
    Ok(out)
}

/// One pack parameter: `param max-files = 8: project, for pack <pack>`.
fn describe_param(param: &ParamOrigin) -> String {
    let set_by = param.set_by.as_ref().map_or_else(
        || "default".to_owned(),
        |layer| describe_rule_origin(&RuleOrigin::Layer(layer.clone())),
    );
    let pack = describe_rule_origin(&RuleOrigin::Pack(param.pack.clone()));
    format!(
        "param {} = {}: {set_by}, for {pack}",
        param.name, param.value
    )
}

/// Render the JSON Schema for `.mindtape/config.toml`, verbatim from
/// [`mindtape::config_schema_json`], the exact same generator `mt install`
/// writes to the XDG `config.schema.json`, so the printed and installed
/// schema can never diverge. Project-independent: it doesn't need a root.
pub(crate) fn render_schema() -> String {
    config_schema_json()
}

/// One human-readable line describing a layer's origin and, for a real path,
/// whether it exists on disk.
fn describe_source(source: &LayerSource) -> String {
    match source {
        LayerSource::Embedded => "embedded: <built-in>".to_owned(),
        LayerSource::Xdg(path) => format!(
            "xdg: {} ({})",
            mindtape::display_path(path),
            existence(path)
        ),
        LayerSource::Dir(path) => format!(
            "dir: {} ({})",
            mindtape::display_path(path),
            existence(path)
        ),
        LayerSource::Project(path) => format!(
            "project: {} ({})",
            mindtape::display_path(path),
            existence(path)
        ),
    }
}

fn existence(path: &Path) -> &'static str {
    if path.is_file() { "exists" } else { "missing" }
}

/// One rule's origin, short form: which kind of layer it came from directly
/// (the layers section above already names each layer's own path), or, for a
/// pack, `pack <source>:<pack>` / `pack <path>`.
fn describe_rule_origin(origin: &RuleOrigin) -> String {
    match origin {
        RuleOrigin::Layer(LayerSource::Embedded) => "embedded".to_owned(),
        RuleOrigin::Layer(LayerSource::Xdg(_)) => "xdg".to_owned(),
        RuleOrigin::Layer(LayerSource::Dir(_)) => "dir".to_owned(),
        RuleOrigin::Layer(LayerSource::Project(_)) => "project".to_owned(),
        RuleOrigin::Pack(PackOrigin::Embedded(name) | PackOrigin::Cached { name, .. }) => {
            format!("pack {name}")
        }
        RuleOrigin::Pack(PackOrigin::Path(path) | PackOrigin::Dir(path)) => {
            format!("pack {}", mindtape::display_path(path))
        }
    }
}

